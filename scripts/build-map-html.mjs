// Bundles Leaflet + src/map/web/* into a single HTML string so the map works
// without fetching any scripts at runtime (only tiles need the network).
// Run after editing anything in src/map/web: `npm run build:map`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const leafletDir = dirname(require.resolve('leaflet/package.json'));

const read = (p) => readFileSync(p, 'utf8');
const leafletJs = read(join(leafletDir, 'dist/leaflet.js'));
const leafletCss = read(join(leafletDir, 'dist/leaflet.css'));
const appJs = read(join(root, 'src/map/web/map.js'));
const appCss = read(join(root, 'src/map/web/map.css'));

// Prevent "</script>" inside inlined code from terminating the tag.
const safe = (s) => s.replace(/<\/(script|style)/gi, '<\\/$1');

const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
<style>${safe(leafletCss)}</style>
<style>${safe(appCss)}</style>
</head>
<body>
<div id="map"></div>
<script>${safe(leafletJs)}</script>
<script>${safe(appJs)}</script>
</body>
</html>`;

const out = `// AUTO-GENERATED by scripts/build-map-html.mjs — do not edit by hand.
/* eslint-disable */
export const MAP_HTML: string = ${JSON.stringify(html)};
`;
writeFileSync(join(root, 'src/map/mapHtml.generated.ts'), out);
console.log(`map html: ${(html.length / 1024).toFixed(0)} KiB`);
